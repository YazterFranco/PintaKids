function furRow(x, y, n, gap, s) {
  let out = '';
  for (let i = 0; i < n; i++) {
    const x0 = x + i * gap;
    out += p(`M${x0} ${y} Q${x0 + s * 0.5} ${y - s} ${x0 + s} ${y}`);
  }
  return out;
}

function noseAnimalSafe(x, y, s = 6) {
  return p(`M${x} ${y + s} Q${x - s} ${y} ${x - s * 0.5} ${y - s * 0.4} Q${x} ${y - s * 0.8} ${x + s * 0.5} ${y - s * 0.4} Q${x + s} ${y} ${x} ${y + s} Z`);
}
